self.addEventListener('install', function (e) {
  e.waitUntil(
    caches.open(CACHE).then(function (c) {
      // cache:'reload' bypasses the HTTP cache so updates always precache fresh files
      return c.addAll(ASSETS.map(function (u) { return new Request(u, { cache: 'reload' }); }));
    }).then(function () { return self.skipWaiting(); })
  );
});

self.addEventListener('activate', function (e) {
  e.waitUntil(
    caches.keys().then(function (keys) {
      return Promise.all(keys.filter(function (k) { return /^guitarlab-v[0-9]+$/.test(k) && k !== CACHE; }).sort(function(a,b){return Number(b.split('v').pop())-Number(a.split('v').pop());}).slice(1).map(function (k) { return caches.delete(k); }));
    }).then(function () { return self.clients.claim(); })
  );
});

self.addEventListener('fetch', function (e) {
  if (e.request.method !== 'GET') return;
  // never intercept cross-origin requests (e.g. the version.json update check)
  if (new URL(e.request.url).origin !== self.location.origin) return;
  e.respondWith(
    caches.open(CACHE).then(function(c){return c.match(e.request, { ignoreSearch: true });}).then(function (hit) {
      return hit || fetch(e.request).then(function (res) {
        var copy = res.clone();
        if (res.ok) caches.open(CACHE).then(function (c) { c.put(e.request, copy).catch(function(){ /* User data is separate; a full asset cache does not erase it. */ }); });
        return res;
      });
    })
  );
});
